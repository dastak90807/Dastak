/* Dastak 90807 — Urdu text for the fee calculators.
   GENERATED by scripts/build_urdu_calcs.py from scripts/ur_hubs/calculator-tools.json. Do not edit by hand.
   Runs only on Urdu pages (<html lang="ur">). It translates text the calculator writes while it runs.
   Fee logic, the PDF slip and the copied summary are not changed. */
(function () {
  var doc = document;
  if ((doc.documentElement.getAttribute('lang') || '') !== 'ur') return;
  var D = /*DICT*/{};
  var M = /*MONTHS*/{};
  var NUM = /\d[\d,]*(?:\.\d+)?/g;
  var LATIN = /[A-Za-z]/;
  var DATE_WORD = new RegExp('\\b(' + Object.keys(M).sort(function (a, b) { return b.length - a.length; }).join('|') + ')\\b', 'g');
  var ATTRS = ['aria-label', 'placeholder', 'title', 'alt'];

  function tr(text) {
    var core = text.replace(/\s+/g, ' ').trim();
    if (!core || !LATIN.test(core)) return null;
    var nums = core.match(NUM) || [];
    var key = core.replace(NUM, '#');
    var u = Object.prototype.hasOwnProperty.call(D, key) ? D[key] : null;
    if (u === null) {
      if (/^[#\s,().\-–/]*$/.test(key.replace(DATE_WORD, ''))) u = key.replace(DATE_WORD, function (w) { return M[w]; });
      else return null;
    }
    var i = 0;
    u = u.replace(/\{(\d)\}|#/g, function (m, k) { return k ? (nums[k - 1] || '') : (i < nums.length ? nums[i++] : '#'); });
    if (/\)\s*$/.test(u)) u += '\u200f'; // right-to-left mark keeps "(Rs. 0)" brackets in place, also in <option>
    return (/^\s/.test(text) ? ' ' : '') + u + (/\s$/.test(text) ? ' ' : '');
  }

  function skip(el) { return !el || el.closest('script,style,noscript,svg'); }

  function doText(n) {
    if (skip(n.parentElement)) return;
    var u = tr(n.nodeValue);
    if (u !== null && u !== n.nodeValue) n.nodeValue = u;
  }

  function doAttrs(el) {
    for (var i = 0; i < ATTRS.length; i++) {
      var v = el.getAttribute(ATTRS[i]);
      if (v) { var u = tr(v); if (u !== null && u !== v) el.setAttribute(ATTRS[i], u); }
    }
  }

  function walk(root) {
    if (root.nodeType === 3) { doText(root); return; }
    if (root.nodeType !== 1 || skip(root)) return;
    doAttrs(root);
    var w = doc.createTreeWalker(root, NodeFilter.SHOW_TEXT | NodeFilter.SHOW_ELEMENT);
    var n;
    while ((n = w.nextNode())) { if (n.nodeType === 3) doText(n); else doAttrs(n); }
  }

  function start() {
    walk(doc.body);
    new MutationObserver(function (list) {
      for (var i = 0; i < list.length; i++) {
        var r = list[i];
        if (r.type === 'characterData') doText(r.target);
        else if (r.type === 'attributes') doAttrs(r.target);
        else for (var j = 0; j < r.addedNodes.length; j++) walk(r.addedNodes[j]);
      }
    }).observe(doc.body, { childList: true, subtree: true, characterData: true, attributes: true, attributeFilter: ATTRS });
  }

  if (doc.readyState === 'loading') doc.addEventListener('DOMContentLoaded', start); else start();
})();
